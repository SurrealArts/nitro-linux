"""Persistent control policy for nitro-linux.

The policy file is the single source of truth for which controls the kernel
module exposes.  It is read on install and upgrade, and materialized into a
modprobe.d drop-in that the kernel reads at load time.

Paths can be overridden for tests and alternate roots:
    NITRO_CONTROLS_CONF   policy file      (/etc/nitro/controls.conf)
    NITRO_MODPROBE_DIR    drop-in dir      (/etc/modprobe.d)
    NITRO_MODULE_PARAMS   loaded params    (/sys/module/nitro/parameters)
    NITRO_CAP_FILE        capabilities     (/sys/devices/platform/nitro/capabilities)
"""

import argparse
import os
import pathlib
import shutil
import subprocess
import sys
import tempfile

KEYS = ("probe", "profile", "fan", "hwmon", "rgb", "coolboost", "kbd_timeout")

DEFAULTS = {
    "probe": False,
    "profile": True,
    "fan": True,
    "hwmon": True,
    "rgb": True,
    "coolboost": True,
    "kbd_timeout": True,
}

# user-facing key -> kernel module parameter
MODULE_PARAMS = {
    "probe": "probe",
    "profile": "disable_profile",
    "fan": "disable_fan",
    "hwmon": "disable_hwmon",
    "rgb": "disable_rgb",
    "coolboost": "disable_coolboost",
    "kbd_timeout": "disable_kbd_timeout",
}

SCHEMA = 1

POLICY_HEADER = (
    "# nitro-linux control policy.\n"
    "# Read on install and upgrade; edit with: sudo nitro controls set <name> <on|off>\n"
    "# Missing keys use the defaults. fan=off also disables CoolBoost.\n"
)


class ControlError(Exception):
    pass


def conf_path():
    return pathlib.Path(
        os.environ.get("NITRO_CONTROLS_CONF", "/etc/nitro/controls.conf"))


def modprobe_dir():
    return pathlib.Path(
        os.environ.get("NITRO_MODPROBE_DIR", "/etc/modprobe.d"))


def options_path():
    return modprobe_dir() / "nitro-controls.conf"


def legacy_path():
    return modprobe_dir() / "nitro-linux.conf"


def params_dir():
    return pathlib.Path(
        os.environ.get("NITRO_MODULE_PARAMS", "/sys/module/nitro/parameters"))


def caps_path():
    return pathlib.Path(
        os.environ.get(
            "NITRO_CAP_FILE", "/sys/devices/platform/nitro/capabilities"))


def onoff(value):
    return "on" if value else "off"


def parse_onoff(value):
    if value == "on":
        return True
    if value == "off":
        return False
    raise ControlError(f"expected on or off, got '{value}'")


def effective(values):
    eff = dict(DEFAULTS)
    eff.update(values)
    if not eff["fan"]:
        eff["coolboost"] = False
    return eff


def _check_contradictions(values, explicit):
    if (
        "fan" in explicit
        and values.get("fan") is False
        and "coolboost" in explicit
        and values.get("coolboost") is True
    ):
        raise ControlError(
            "fan=off also disables CoolBoost; set coolboost=off")


def read_policy(path=None):
    path = path or conf_path()
    values = {}
    seen = set()
    try:
        text = path.read_text()
    except FileNotFoundError:
        return values, set()
    except (OSError, UnicodeDecodeError) as exc:
        raise ControlError(f"cannot read {path}: {exc}")

    for number, line in enumerate(text.splitlines(), 1):
        stripped = line.strip()
        if not stripped or stripped.startswith("#"):
            continue
        if "=" not in stripped:
            raise ControlError(f"{path}:{number}: expected key=value")
        key, _, raw = stripped.partition("=")
        key = key.strip().lower()
        raw = raw.strip().lower()
        if key in seen:
            raise ControlError(f"{path}:{number}: duplicate key '{key}'")
        seen.add(key)
        if key == "schema":
            if raw != str(SCHEMA):
                raise ControlError(
                    f"{path}:{number}: unsupported schema '{raw}' "
                    f"(expected {SCHEMA})")
            continue
        if key not in KEYS:
            raise ControlError(f"{path}:{number}: unknown key '{key}'")
        if raw not in ("on", "off"):
            raise ControlError(
                f"{path}:{number}: {key} must be on or off, got '{raw}'")
        values[key] = raw == "on"

    _check_contradictions(values, set(values))
    return values, set(values)


def render_module_options(eff):
    options = []
    if eff["probe"]:
        options.append("probe=1")
    for key in ("profile", "fan", "hwmon", "rgb", "coolboost", "kbd_timeout"):
        if not eff[key]:
            options.append(f"{MODULE_PARAMS[key]}=1")
    return options


def render_options_text(options):
    if not options:
        return None
    return (
        "# Generated by 'nitro controls' from "
        f"{conf_path()}. Do not edit.\n"
        f"options nitro {' '.join(options)}\n"
    )


def render_policy(values):
    eff = effective(values)
    lines = [POLICY_HEADER.rstrip("\n"), f"schema={SCHEMA}"]
    lines.extend(f"{key}={onoff(eff[key])}" for key in KEYS)
    return "\n".join(lines) + "\n"


def _write(path, text, mode=0o644):
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(prefix=f".{path.name}.", dir=str(path.parent))
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as handle:
            handle.write(text)
        os.chmod(tmp, mode)
        os.replace(tmp, path)
    except BaseException:
        try:
            os.unlink(tmp)
        except OSError:
            pass
        raise


def apply_changes(changes, current_values):
    path = conf_path()
    if not path.exists():
        final = dict(current_values)
        final.update(changes)
        _write(path, render_policy(final))
        return

    lines = path.read_text().splitlines()
    index = {}
    for number, line in enumerate(lines):
        stripped = line.strip()
        if not stripped or stripped.startswith("#"):
            continue
        key = stripped.partition("=")[0].strip().lower()
        if key in changes and key not in index:
            index[key] = number

    for key in KEYS:
        if key not in changes:
            continue
        new_line = f"{key}={onoff(changes[key])}"
        if key in index:
            lines[index[key]] = new_line
        else:
            lines.append(new_line)

    _write(path, "\n".join(lines) + "\n")


def read_options():
    path = options_path()
    try:
        text = path.read_text()
    except FileNotFoundError:
        return {}
    except OSError as exc:
        raise ControlError(f"cannot read {path}: {exc}")

    found = {}
    for line in text.splitlines():
        stripped = line.strip()
        if not stripped or stripped.startswith("#"):
            continue
        parts = stripped.split()
        if len(parts) < 2 or parts[0] != "options" or parts[1] != "nitro":
            continue
        for token in parts[2:]:
            if "=" in token:
                name, _, value = token.partition("=")
                found[name] = value
    return found


def scan_foreign():
    directory = modprobe_dir()
    warnings = []
    try:
        files = sorted(directory.glob("*.conf"))
    except OSError:
        return warnings
    for path in files:
        if path.name == options_path().name:
            continue
        try:
            lines = path.read_text().splitlines()
        except (OSError, UnicodeDecodeError):
            continue
        for number, line in enumerate(lines, 1):
            stripped = line.strip()
            if not stripped or stripped.startswith("#"):
                continue
            parts = stripped.split()
            if len(parts) >= 2 and parts[0] == "options" and parts[1] == "nitro":
                warnings.append(f"{path}:{number}: {stripped}")
    return warnings


def migrate_legacy(values, explicit, remove):
    path = legacy_path()
    if not path.is_file():
        return values, explicit, False
    try:
        lines = path.read_text(errors="replace").splitlines()
    except OSError:
        return values, explicit, False
    if not lines or "read-only probe mode" not in lines[0]:
        return values, explicit, False

    has_probe = False
    for line in lines:
        parts = line.strip().split()
        if (
            len(parts) >= 3
            and parts[0] == "options"
            and parts[1] == "nitro"
            and "probe=1" in parts[2:]
        ):
            has_probe = True
    if not has_probe:
        return values, explicit, False

    values = dict(values)
    policy_off = "probe" in explicit and values.get("probe") is False
    if policy_off:
        values["probe"] = False
        print(
            f"warning: {path} requests probe mode but the policy sets "
            "probe=off; the policy wins",
            file=sys.stderr,
        )
    else:
        values["probe"] = True
        explicit = set(explicit) | {"probe"}
    if remove:
        try:
            path.unlink()
        except OSError as exc:
            print(f"warning: cannot remove {path}: {exc}", file=sys.stderr)
    return values, explicit, not policy_off


def sync(quiet=False, values=None):
    values = read_policy()[0] if values is None else values
    eff = effective(values)
    text = render_options_text(render_module_options(eff))
    path = options_path()

    changed = False
    if text is None:
        if path.exists():
            try:
                path.unlink()
            except OSError as exc:
                raise ControlError(f"cannot remove {path}: {exc}")
            changed = True
    else:
        try:
            current = path.read_text()
        except FileNotFoundError:
            current = None
        except OSError as exc:
            raise ControlError(f"cannot read {path}: {exc}")
        if current != text:
            _write(path, text)
            changed = True

    if not quiet:
        for warning in scan_foreign():
            print(f"warning: {warning}", file=sys.stderr)
        if changed:
            print(f"{'wrote' if text else 'removed'} {path}")
    return changed


def _read_bool(path):
    try:
        text = path.read_text().strip().lower()
    except OSError:
        return None
    if text in ("y", "1", "on", "true"):
        return True
    if text in ("n", "0", "off", "false"):
        return False
    return None


def consistency(eff):
    errors = []
    expected = {
        token.partition("=")[0]: token.partition("=")[2]
        for token in render_module_options(eff)
    }
    actual = read_options()
    if expected != actual:
        fmt = lambda table: ", ".join(
            f"{key}={value}" for key, value in sorted(table.items())
        ) or "none"
        errors.append(
            f"{options_path()}: has {fmt(actual)}; policy expects {fmt(expected)}")
    elif not expected and options_path().exists():
        errors.append(
            f"{options_path()}: exists but the policy needs no options")

    directory = params_dir()
    if not directory.is_dir():
        return errors, True

    for key in KEYS:
        name = MODULE_PARAMS[key]
        want = eff[key] if key == "probe" else not eff[key]
        live = _read_bool(directory / name)
        if live is None:
            errors.append(f"module parameter {name}: missing")
        elif live != want:
            errors.append(
                f"module parameter {name}: {onoff(live)} "
                f"(policy expects {onoff(want)})")
    return errors, False


def cmd_show():
    values, _ = read_policy()
    eff = effective(values)
    exists = conf_path().exists()
    print(f"policy: {conf_path()}" + ("" if exists else " (missing; defaults)"))
    for key in KEYS:
        if key in values:
            origin = "file"
        elif key == "coolboost" and not eff["fan"]:
            origin = "implied by fan=off"
        else:
            origin = "default"
        print(f"  {key:<12} {onoff(eff[key]):<3}  ({origin})")

    print(f"module options: {options_path()}")
    options = render_module_options(eff)
    if options:
        print(f"  options nitro {' '.join(options)}")
    else:
        print("  (none)")

    caps = None
    try:
        caps = caps_path().read_text().strip()
    except OSError:
        pass
    if caps:
        print(f"kernel capabilities: {caps}")

    directory = params_dir()
    if not directory.is_dir():
        print("live module: not loaded")
    else:
        for key in KEYS:
            name = MODULE_PARAMS[key]
            live = _read_bool(directory / name)
            print(f"  {name}: {'?' if live is None else onoff(live)}")

    for warning in scan_foreign():
        print(f"warning: {warning}", file=sys.stderr)

    errors, unknown = consistency(eff)
    if unknown:
        print("status: unknown (module not loaded)")
    elif errors:
        print("status: out of sync (run 'sudo nitro controls apply')")
    else:
        print("status: in sync")
    return 0


def cmd_check():
    values, _ = read_policy()
    eff = effective(values)
    errors, unknown = consistency(eff)
    for error in errors:
        print(error)
    if unknown:
        print("module not loaded; cannot verify the loaded options")
        return 2
    if errors:
        return 1
    print("controls: in sync")
    return 0


def cmd_sync(args):
    changed = sync(quiet=args.quiet)
    if not args.quiet:
        print("updated" if changed else "unchanged")
    return 0


def cmd_set(args):
    value = parse_onoff(args.value)
    values, explicit = read_policy()
    changes = {args.name: value}
    if args.name == "fan" and not value:
        changes["coolboost"] = False

    final = dict(values)
    final.update(changes)
    _check_contradictions(final, explicit | set(changes))

    if args.dry_run:
        print(f"would set {args.name}={onoff(value)} in {conf_path()}")
        if args.name == "fan" and not value:
            print("would also set coolboost=off")
        return 0

    apply_changes(changes, values)
    sync(quiet=True)
    print(f"{args.name}={onoff(value)}; {conf_path()} updated")
    if args.name == "fan" and not value:
        print("note: fan=off also disables CoolBoost")
    print("apply now with 'sudo nitro controls apply', or reboot")
    return 0


def parse_features(items):
    names = set()
    for item in items:
        for part in item.split(","):
            name = part.strip().lower()
            if not name:
                continue
            if name not in KEYS:
                raise ControlError(
                    f"unknown control '{name}' (valid: {', '.join(KEYS)})")
            names.add(name)
    return names


def cmd_install(args):
    enabled = parse_features(args.with_)
    disabled = parse_features(args.without)
    overlap = enabled & disabled
    if overlap:
        raise ControlError(
            "control named in both --with and --without: "
            + ", ".join(sorted(overlap)))
    if "fan" in disabled and "coolboost" in enabled:
        raise ControlError(
            "--without=fan also disables CoolBoost; drop --with=coolboost")

    values, explicit = read_policy()
    migrated = False
    if not args.no_save:
        values, explicit, migrated = migrate_legacy(
            values, explicit, remove=not args.dry_run)

    changes = {}
    for key in KEYS:
        if key in enabled:
            changes[key] = True
        if key in disabled:
            changes[key] = False
    if "fan" in disabled:
        changes["coolboost"] = False
    if migrated:
        changes["probe"] = True

    final = dict(values)
    final.update(changes)
    _check_contradictions(final, explicit | set(changes))
    eff = effective(final)

    if args.dry_run:
        exists = conf_path().exists()
        print(
            f"policy: {conf_path()}"
            + ("" if exists else " (missing; would be created)"))
        for key in KEYS:
            print(f"  {key}={onoff(eff[key])}")
        options = render_module_options(eff)
        print(
            f"would write {options_path()}: "
            + (f"options nitro {' '.join(options)}" if options else "(none)"))
        return 0

    existed = conf_path().exists()
    if not args.no_save and (changes or migrated or not existed):
        apply_changes(changes, values)

    changed = sync(quiet=True, values=final)
    for warning in scan_foreign():
        print(f"warning: {warning}", file=sys.stderr)

    if not args.quiet:
        print(f"controls: {conf_path()}")
        for key in KEYS:
            print(f"  {key}={onoff(eff[key])}")
        print(f"module options: {'updated' if changed else 'unchanged'}")
    if args.boot_notice and changed:
        print("reboot to apply the changed control options")
    return 0


def cmd_apply(args):
    if os.geteuid() != 0:
        raise ControlError("run with sudo")
    sync(quiet=True)

    systemctl = shutil.which("systemctl")
    use_systemd = (
        systemctl is not None and pathlib.Path("/run/systemd/system").is_dir())
    active = False
    if use_systemd:
        active = subprocess.run(
            [systemctl, "is-active", "--quiet", "nitrod"],
            capture_output=True, text=True).returncode == 0
        if active:
            subprocess.run(
                [systemctl, "stop", "nitrod"],
                capture_output=True, text=True)

    was_loaded = params_dir().is_dir()
    try:
        result = subprocess.run(
            ["modprobe", "-r", "nitro"], capture_output=True, text=True)
        if was_loaded and result.returncode != 0:
            detail = result.stderr.strip() or f"exit {result.returncode}"
            raise ControlError(f"modprobe -r nitro failed: {detail}")
        result = subprocess.run(
            ["modprobe", "nitro"], capture_output=True, text=True)
        if result.returncode != 0:
            detail = result.stderr.strip() or f"exit {result.returncode}"
            raise ControlError(f"modprobe nitro failed: {detail}")
    finally:
        if active:
            subprocess.run(
                [systemctl, "start", "nitrod"],
                capture_output=True, text=True)

    print("reloaded nitro; control changes are active")
    return 0


def build_parser():
    parser = argparse.ArgumentParser(
        prog="nitro controls",
        description="Persist which controls the nitro module exposes.")
    sub = parser.add_subparsers(dest="command", required=True)

    sub.add_parser("show", help="show policy, drop-in, and loaded options")
    sub.add_parser("check", help="verify policy, drop-in, and loaded options")
    sub.add_parser("apply", help="reload the module to apply the policy now")

    set_parser = sub.add_parser("set", help="change one control")
    set_parser.add_argument("name", choices=KEYS)
    set_parser.add_argument("value", help="on or off")
    set_parser.add_argument(
        "--dry-run", action="store_true", help="print without writing")

    sync_parser = sub.add_parser("sync", help="materialize the policy")
    sync_parser.add_argument("--quiet", action="store_true")

    install_parser = sub.add_parser(
        "install", help="create and sync the policy from an installer")
    install_parser.add_argument(
        "--with", dest="with_", action="append", default=[], metavar="LIST",
        help="controls to enable (comma separated)")
    install_parser.add_argument(
        "--without", action="append", default=[], metavar="LIST",
        help="controls to disable (comma separated)")
    install_parser.add_argument(
        "--no-save", action="store_true",
        help="apply overrides without changing the policy")
    install_parser.add_argument(
        "--dry-run", action="store_true", help="print without writing")
    install_parser.add_argument("--quiet", action="store_true")
    install_parser.add_argument(
        "--boot-notice", action="store_true",
        help="print a reboot note when the drop-in changed")
    return parser


def main(argv=None):
    args = build_parser().parse_args(argv)
    try:
        if args.command == "show":
            return cmd_show()
        if args.command == "check":
            return cmd_check()
        if args.command == "sync":
            return cmd_sync(args)
        if args.command == "set":
            return cmd_set(args)
        if args.command == "install":
            return cmd_install(args)
        if args.command == "apply":
            return cmd_apply(args)
    except ControlError as exc:
        print(f"nitro controls: {exc}", file=sys.stderr)
        return 1
    except PermissionError as exc:
        print(f"nitro controls: {exc}; run with sudo", file=sys.stderr)
        return 1
    except OSError as exc:
        print(f"nitro controls: {exc}", file=sys.stderr)
        return 1
    return 2


if __name__ == "__main__":
    sys.exit(main())
